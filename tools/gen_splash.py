# NORILSK: the splash screen's logo (assets/splash/mark.png, word.png: tools/make_splash.py) to a C header. Each image
# is brought to 16 colours of its own (RGB565, byte-swapped as the panel takes them), its pixels 4 bits each, two a
# byte (high nibble first), rows top to bottom.
"""tools/gen_splash.py OUT.h"""
import sys
from pathlib import Path

from PIL import Image

SRC = Path(__file__).resolve().parents[1] / "assets" / "splash"


def rgb565_swapped(r, g, b):
    c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return ((c & 0xFF) << 8) | (c >> 8)


def image(name):
    im = Image.open(SRC / f"{name}.png").convert("RGB")
    q = im.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:48]
    pal += [0] * (48 - len(pal))
    w, h = q.size
    px = list(q.tobytes())
    data = bytearray()
    for y in range(h):
        row = px[y * w:(y + 1) * w] + ([0] if w % 2 else [])
        for i in range(0, len(row), 2):
            data.append((row[i] << 4) | row[i + 1])
    cols = [rgb565_swapped(pal[3 * k], pal[3 * k + 1], pal[3 * k + 2]) for k in range(16)]
    up = name.upper()
    out = [f"static const uint16_t SPLASH_{up}_PAL[16] = {{" + ", ".join(f"0x{c:04X}" for c in cols) + "};",
           f"static const uint8_t SPLASH_{up}_PX[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"#define SPLASH_{up}_W {w}u")
    out.append(f"#define SPLASH_{up}_H {h}u")
    return "\n".join(out)


if __name__ == "__main__":
    body = "\n".join(image(n) for n in ("mark", "word"))
    Path(sys.argv[1]).write_text("/* generated by tools/gen_splash.py from assets/splash/: the splash screen's logo */\n"
                                 + body + "\n")
