# NORILSK: every message the firmware's screen says, for the host's test that each fits (host fit) -- say("...") as
# written, say_n("a", n, "b") with the widest numbers it may carry, and the few built otherwise (listed here by hand).
# Out: build/gen/norilsk_says.h (static const char *const SAYS[]).   tools/list_says.py OUT
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "firmware" / "src"
says = set()
for f in sorted(SRC.glob("*.c")):
    t = f.read_text()
    for m in re.finditer(r'\bsay\((.*?)\);', t, re.S):   # (every literal in it: a ternary's both)
        for lit in re.findall(r'"([^"]*)"', m[1]):
            says.add(lit)
    for m in re.finditer(r'\bsay_n\((.*?)\);', t, re.S):  # (the prefixes, a number, the suffix)
        lits = re.findall(r'"([^"]*)"', m[1])
        if len(lits) >= 2:
            for pre in lits[:-1]:
                for n in ("100", "-24", "64"):
                    says.add(pre + n + lits[-1])
for x in ("MOVE +24", "MOVE -24", "PAN L20", "PAN R20", "PAN C", "LEVEL OFF"):   # (the ternaries)
    says.add(x)
out = Path(sys.argv[1] if len(sys.argv) > 1 else "build/gen/norilsk_says.h")
out.write_text("/* generated by tools/list_says.py */\nstatic const char *const SAYS[] = {\n" +
               "".join(f'    "{s}",\n' for s in sorted(says) if s) + "};\n")
print(f"{out}: {len(says)} messages")
